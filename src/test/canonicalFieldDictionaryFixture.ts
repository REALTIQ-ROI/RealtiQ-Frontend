import type { CanonicalFieldDictionary, RuntimeCanonicalField } from '../services/canonicalFieldService';

type Target = 'property' | 'project' | 'project_unit';

const field = (
  key: string,
  dataType: string,
  allowedValues?: unknown,
  target: Target = 'property',
  extras: Partial<RuntimeCanonicalField> = {},
): RuntimeCanonicalField => ({
  key,
  kind: dataType,
  dataType,
  level: target === 'property' ? 'property' : 'project',
  requiredness: 'optional',
  condition: null,
  allowedValues,
  catalogue: null,
  minimum: null,
  maximum: null,
  nullableWhen: null,
  unit: null,
  nullMeaning: '',
  zeroMeaning: '',
  unsetMeaning: '',
  inheritance: '',
  publication: '',
  searchable: false,
  searchUse: null,
  visibility: 'public',
  importable: true,
  entityApplicability: { sourceLevel: target, mutationTargets: [target] },
  validationConstraints: {},
  editableTargets: [target],
  mutationOperations: { [target]: { set: true, setNull: true, unset: true, resetToInherit: true } },
  systemOwned: false,
  transitionManaged: false,
  workflowOperations: [],
  readOnly: false,
  ...extras,
});

